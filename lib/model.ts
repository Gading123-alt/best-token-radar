// Token Radar — model "radar-2".
//
// One sealed snapshot in, one ranked board out. The board ranks EVERY protocol
// that records no token and is not a wrapped, staked or bridged product of a
// token that already trades: the snapshot's 40-protocol watchlist is the
// floor, and the pre-token protocols below that floor are the early radar the
// bounty exists to find. The watchlist's own exclusion rule is applied to the
// whole board — a wrapped or staked product (WBTC, Binance staked ETH,
// USDT0) is Bitcoin or ETH in another form, not a protocol still waiting on
// a launch of its own, so the house leaves it off the watchlist and this
// board leaves it off entirely. Protocols whose token already trades are
// never ranked; the 24 largest by market cap are set aside as a separate
// "live" view, shown at the market's own value.
//
// Implied value follows only from the snapshot's own figures — TVL, 7-day
// growth, age (days since DefiLlama began tracking it) and chain breadth.
// No protocol name is ever special-cased; the same function scores every row:
//
//   base        = tvl_usd x 0.25
//   growth      = clamp(change_7d, -60, 120) per cent; 0 when unreported
//   growthMult  = 1 + (growth / 100) x 0.5
//   maturity    = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365)
//   breadth     = 1 + 0.02 x min(chains - 1, 8)   (1 chain: 1.00, 9+ chains: 1.16)
//   implied     = max(1, round(base x growthMult x maturity x breadth))
//
// Why breadth: a protocol live on more chains has more surfaces a reader can
// farm and more distribution for a future token, and the snapshot itself
// counts the chains. Why 0.25: a token launch is commonly valued near a
// quarter of the value the protocol already secures — a starting multiple the
// dashboard states in the open, not a hidden guess. Growth is clamped so one
// hot week cannot dominate; maturity rewards protocols that survived long
// enough to be tracked without issuing a token.
//
// Farm plans are derived the same way, from category, chains, TVL and age:
// the category picks the action, TVL picks the capital, age picks the hold.
// Every step states what it costs and how long it takes. Nothing here claims
// a token is announced or guaranteed: the snapshot records no token, and the
// plan says so.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

